// ---------------------------------------------------------------------------
// Dummy traces — generate realistic hook sequences modeled on
// pixel-office HookPayloadFactory::todoAppLifecycle and the scrubbed
// fixtures under external/pixel-office/tests/Fixtures/traces.
// ---------------------------------------------------------------------------

import * as fs from 'fs';
import * as path from 'path';
import { HookEventFactory } from '../base/factories';
import type { HookEvent, TranscriptMsg } from '../base/types';
import type { DummyCommand } from './commands';

export interface DummyTurn {
  events: HookEvent[];
  stdout: string;
  transcript: TranscriptMsg[];
}

function listWorkspace(root: string): string {
  try {
    const names = fs.readdirSync(root).slice(0, 20);
    return names.map(n => `- ${n}`).join('\n') || '(empty)';
  } catch { return '(unreadable)'; }
}

function readFileSafe(root: string, rel: string): string {
  const full = path.resolve(root, rel);
  if (!full.startsWith(path.resolve(root))) { return '(refused path outside workspace)'; }
  try { return fs.readFileSync(full, 'utf8').slice(0, 800); }
  catch { return `(missing ${rel})`; }
}

export function generateDummyTurn(root: string, cmd: DummyCommand, sessionId: string): DummyTurn {
  const factory = HookEventFactory.make({ cwd: root, sessionId, provider: 'dummy' });
  const events: HookEvent[] = [factory.sessionStart(), factory.userPromptSubmit(cmd.raw.slice(0, 400))];
  const transcript: TranscriptMsg[] = [{ role: 'user', text: cmd.raw.slice(0, 400), ts: Date.now() }];
  const lines: string[] = [];

  const tool = (name: string, input: Record<string, unknown>, output: string) => {
    const id = `call-dummy-${name}-${Date.now().toString(36)}`;
    events.push(factory.toolStart(name, input, id));
    events.push(factory.toolEnd(name, { ...input, output }, id));
    transcript.push({ role: 'tool', text: `🔧 ${name}(${JSON.stringify(input).slice(0, 200)})`, ts: Date.now() });
    transcript.push({ role: 'tool', text: `↳ ${output.slice(0, 200)}`, ts: Date.now() });
  };

  switch (cmd.kind) {
    case 'hello': {
      const msg = 'Hello from the dummy agent. I am online and ready for office tasks.';
      events.push(factory.notification(msg));
      events.push(factory.agentMessage(msg));
      lines.push(msg);
      break;
    }
    case 'list': {
      const listing = listWorkspace(root);
      tool('list_dir', { target_directory: root }, listing);
      const msg = `Workspace listing:\n${listing}`;
      events.push(factory.agentMessage(msg));
      lines.push(msg);
      break;
    }
    case 'read': {
      const rel = cmd.arg ?? 'README.md';
      const body = readFileSafe(root, rel);
      tool('read_file', { target_file: rel }, body);
      const msg = `Read ${rel} (${body.length} chars).`;
      events.push(factory.agentMessage(msg));
      lines.push(msg);
      lines.push(body);
      break;
    }
    case 'write': {
      const rel = cmd.arg ?? 'notes.md';
      const content = `# Dummy note\n\nGenerated by dummy agent.\n`;
      const full = path.resolve(root, rel);
      if (full.startsWith(path.resolve(root))) {
        try { fs.mkdirSync(path.dirname(full), { recursive: true }); fs.writeFileSync(full, content, 'utf8'); } catch { /* */ }
      }
      tool('Write', { file_path: rel, content }, `Wrote ${rel}`);
      const msg = `Wrote ${rel}.`;
      events.push(factory.agentMessage(msg));
      lines.push(msg);
      break;
    }
    case 'bash': {
      const command = cmd.arg ?? 'ls -la';
      tool('Bash', { command }, `$ ${command}\n(dummy) ok`);
      const msg = `Ran \`${command}\` (simulated).`;
      events.push(factory.agentMessage(msg));
      lines.push(msg);
      break;
    }
    case 'todo': {
      events.push(factory.todoUpdated());
      const msg = 'Updated the todo list: scaffold done, implement next.';
      events.push(factory.agentMessage(msg));
      lines.push(msg);
      break;
    }
    case 'complete': {
      const todoPath = path.join(root, 'TODO.md');
      try {
        const text = fs.readFileSync(todoPath, 'utf8');
        const next = text.replace(/^(\s*[-*]\s*)\[\s\](\s*.+)$/m, '$1[x]$2');
        if (next !== text) { fs.writeFileSync(todoPath, next, 'utf8'); }
      } catch { /* no TODO.md */ }
      tool('Edit', { file_path: 'TODO.md' }, 'Checked off the first pending task');
      const msg = 'Marked the first pending TODO item complete.';
      events.push(factory.agentMessage(msg));
      lines.push(msg);
      break;
    }
    case 'lifecycle':
    default: {
      const lifecycle = factory.todoAppLifecycle();
      // Drop the factory's own SessionStart/UserPromptSubmit — we already emitted those.
      events.push(...lifecycle.slice(2));
      const msg = 'I will scaffold a sample todo app (list → read → write) and update the backlog.';
      lines.push(msg);
      transcript.push({ role: 'assistant', text: msg, ts: Date.now() });
      events.push(factory.stop());
      return { events, stdout: lines.join('\n') + '\n', transcript };
    }
  }

  events.push(factory.stop());
  events.push(factory.sessionEnd());
  const assistant = lines.join('\n');
  transcript.push({ role: 'assistant', text: assistant, ts: Date.now() });
  return { events, stdout: assistant + '\n', transcript };
}
